export function findCalories(productName: string): number | null {
  const lower = productName.toLowerCase().trim();

  if (CALORIES_DB[lower] !== undefined) return CALORIES_DB[lower];

  const match = Object.keys(CALORIES_DB).find(
    (key) => lower.includes(key) || key.includes(lower)
  );

  return match ? CALORIES_DB[match] : null;
}
